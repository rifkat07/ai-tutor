async def seed_fgos_textbooks():
    print("=" * 75)
    print("📚 МАСШТАБНОЕ НАПОЛНЕНИЕ БАЗЫ УЧЕБНИКАМИ ФГОС 2023–2026 (5–11 КЛАССЫ)")
    print("=" * 75)

    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    async with AsyncSessionLocal() as db:
        total_books = 0
        total_exercises = 0

        for book_info in FGOS_TEXTBOOKS_DATA:
            textbook = Textbook(
                id=uuid.uuid4(),
                subject=book_info["subject"],
                grade=book_info["grade"],
                author=book_info["author"],
                title=book_info["title"],
                publication_year=book_info.get("year", 2023),
            )
            db.add(textbook)
            await db.commit()
            await db.refresh(textbook)
            total_books += 1

            for ex_info in book_info["exercises"]:
                db_ex = TextbookExercise(
                    id=uuid.uuid4(),
                    textbook_id=textbook.id,
                    exercise_number=ex_info["num"],
                    chapter_title=ex_info["chapter"],
                    condition_text=ex_info["cond"],
                    official_solution_hint=ex_info.get("hint", ""),
                )
                db.add(db_ex)
                total_exercises += 1

            await db.commit()
            print(f"  ✅ Загружен: [{book_info['subject'].upper()} • {book_info['grade']} кл] {book_info['title']} ({len(book_info['exercises'])} упражнений)")

        print("\n" + "=" * 75)
        print(f"🎉 УСПЕШНО ЗАГРУЖЕНО {total_books} УЧЕБНИКОВ ФГОС И {total_exercises} ОЦИФРОВАННЫХ УПРАЖНЕНИЙ!")
        print("=" * 75)


if __name__ == "__main__":
    asyncio.run(seed_fgos_textbooks())
