async def seed_database():
    print("=" * 75)
    print("🌱 ЧИСТОЕ НАПОЛНЕНИЕ БАЗЫ ЗАДАНИЯМИ ФИПИ (С ПОЛНЫМ УДАЛЕНИЕМ ДУБЛИКАТОВ)")
    print("=" * 75)

    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    async with AsyncSessionLocal() as db:
        # 1. Очищаем старые записи источника FIPI_Official_Bank перед заливкой
        await db.execute(delete(RAGTask).where(RAGTask.source == "FIPI_Official_Bank"))
        await db.commit()

        added_count = 0

        # 2. Добавляем чистый расширенный банк с детерминированными UUID
        for task_data in EXPANDED_FIPI_TASKS:
            # Детерминированный UUID на основе id_key исключает любые дубликаты
            deterministic_uuid = uuid.uuid5(uuid.NAMESPACE_DNS, task_data["id_key"])

            task = RAGTask(
                id=deterministic_uuid,
                subject=task_data["subject"],
                task_number=task_data["task_number"],
                fipi_code=task_data["fipi_code"],
                condition_text=task_data["condition_text"],
                solution_text=task_data["solution_text"],
                source="FIPI_Official_Bank",
            )
            db.add(task)
            added_count += 1

        await db.commit()
        print(f"✅ Успешно занесено {added_count} уникальных эталонных прототипов ФИПИ (0 дубликатов)!")
        print("=" * 75)


if __name__ == "__main__":
    asyncio.run(seed_database())
