def render_template(template: str, **kwargs) -> str:
    """Безопасная замена меток [ключ] без конфликтов с фигурными скобками LaTeX { }."""
    res = template
    for k, v in kwargs.items():
        res = res.replace(f"[{k}]", str(v))
    return res


